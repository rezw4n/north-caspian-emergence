"""Table 3 and a Supplementary Table for H3, as LaTeX that prints every number through
\\metric{...} (CLAUDE.md integrity rule 2).

1. Table 3 (emerged area and exposure at 1 m and 2 m below the 2026 level, domain): for
   each product, the fused surface and the product as used (uncorrected), the estimate
   with its 90% interval. Written into manuscript/sections/tables_draft.tex between the
   markers "% BEGIN T3" and "% END T3" (the rest of the file is kept).
2. Supplementary Table: the calendar year at which each published pathway reaches each
   scenario depth (results/emergence/main/scenario_dates.csv), written to
   manuscript/sections/ed_tables_h3_draft.tex. Pathways whose source is not yet in
   refs/verification.csv are left out and named in a note.

Every key is checked against results/metrics.json; the script stops on a missing key.

Usage: python figures/tab_h3.py
"""

from __future__ import annotations

import csv
import sys

import _common as C
import pandas as pd

from caspian.config import RESULTS

TABLES = C.ROOT / "manuscript" / "sections" / "tables_draft.tex"
ED = C.ROOT / "manuscript" / "sections" / "ed_tables_h3_draft.tex"
PK = {"gebco_2026": "gebco2026", "gebco_2022": "gebco2022", "etopo_2022": "etopo2022", "srtm15p_v2.7": "srtm15p",
      "etopo1": "etopo1"}
PROD_TEX = {"gebco_2026": "GEBCO\\_2026", "gebco_2022": "GEBCO\\_2022", "etopo_2022": "ETOPO 2022",
            "srtm15p_v2.7": "SRTM15+ V2.7", "etopo1": "ETOPO1"}
ROWS = [("area", "Emerged area (km\\textsuperscript{2})"),
        ("platforms", "Platforms and wells newly onshore"),
        ("pipelines", "Pipeline length emerged (km)"),
        ("channels", "Channel length emerged (km)"),
        ("ports", "Ports losing the sea within \\metric{h3.port_access_km}~km"),
        ("settlements", "Settlements losing the sea within \\metric{h3.coast_km}~km"),
        ("worldcover", "WorldCover 2021 herbaceous wetland (km\\textsuperscript{2})")]
ROWS_ED = [("osm_wetlands", "OSM wetland emerged (km\\textsuperscript{2})"),
           ("gwl", "GWL\\_FCS30 2020 wetland (km\\textsuperscript{2})"),
           ("glwd", "GLWD v2 wetland (km\\textsuperscript{2})")]
SURF = {"fused": "fused", "uncorrected": "as used"}
SOURCE_TEX = {"hoseini2025": "\\citet{hoseini2025}", "samant2023": "\\citet{samant2023}"}


class Keys:
    def __init__(self, metrics: dict):
        self.m, self.missing = metrics, []

    def __call__(self, key: str) -> str:
        if key not in self.m:
            self.missing.append(key)
        return f"\\metric{{{key}}}"


def cell(k: Keys, row: str, p: str, surface: str, sc: str) -> str:
    if row == "area":
        b = f"h3.emergence.{PK[p]}.{surface}.{sc}"
        return f"{k(b + '.estimate_km2')}\\newline [{k(b + '.lo_km2')}, {k(b + '.hi_km2')}]"
    b = f"h3.exposure.{row}.{PK[p]}.{surface}.{sc}"
    return f"{k(b + '.amount')}\\newline [{k(b + '.lo')}, {k(b + '.hi')}]"


def body(k: Keys, rows, scenarios) -> list[str]:
    out = []
    for sc in scenarios:
        if len(scenarios) > 1:
            out.append(f"\\multicolumn{{{2 + len(C.PRODUCTS)}}}{{l}}{{\\textbf{{{sc}~m below the 2026 level}}}} \\\\")
        for row, name in rows:
            for j, (surf, sname) in enumerate(SURF.items()):
                lead = name if j == 0 else ""
                out.append(f"{lead} & {sname} & " + " & ".join(cell(k, row, p, surf, sc) for p in C.PRODUCTS) + " \\\\")
        out.append("\\hline")
    return out


COLS = "p{2.55cm}p{1.0cm}" + "p{2.0cm}" * 5
NOTE = ("For each product: the fused surface (the waterline DEM inside the observed range, the product corrected by the "
        "hindcast error model below it) and the product as used (uncorrected). Estimate, with the "
        "\\metric{params.conformal_level} split-conformal interval below it. Area intervals are calibrated on the "
        "absolute hindcast errors of held-out units (leave-one-epoch-out for the corrected product; "
        "\\metric{h3.n_scores.gebco2026.fused} scores for GEBCO\\_2026, for example) and clipped at zero; exposure "
        "intervals are the exposure at the levels at which the surface's emergence reaches the area-interval bounds. "
        "Each surface is referenced to its own 2026 shoreline, so exposure counts only features that the surface puts "
        "in the sea (or within the access distance of it) in 2026. Counts are features; lengths and areas are the "
        "parts that emerge.")


def header() -> list[str]:
    return ["\\begin{tabular}{" + COLS + "}", "\\hline",
            " & Surface & " + " & ".join(PROD_TEX[p] for p in C.PRODUCTS) + " \\\\", "\\hline"]


def t3(k: Keys) -> list[str]:
    out = ["% BEGIN T3 (generated by figures/tab_h3.py from results/metrics.json keys; do not edit by hand)",
           "\\begin{table}[!htbp]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{2.5pt}",
           "\\caption{\\textbf{Emerged area and exposure 1~m below the 2026 level (H3).} Domain; 2026 level "
           "\\metric{h3.level_2026_m}~m on the DAHITI reference (mean of the \\metric{h3.level_2026.n_records} DAHITI "
           "records of 2026). " + NOTE + " The wetland layer is an open-licence habitat stand-in, not an authoritative "
           "habitat map. The same at 2~m, and three further habitat stand-ins: Supplementary Tables~"
           "\\ref{tab:ed_h3_2m} and~\\ref{tab:ed_h3_habitat}. Data \\textcopyright{} OpenStreetMap contributors (ODbL).}",
           "\\label{tab:h3}"] + header()
    out += body(k, ROWS, ["1"])
    out += ["\\end{tabular}", "\\end{table}", "% END T3"]
    return out


def t3_2m(k: Keys) -> list[str]:
    out = ["\\begin{table}[!htbp]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{2.5pt}",
           "\\caption{\\textbf{Emerged area and exposure 2~m below the 2026 level (H3).} As Table~\\ref{tab:h3}, "
           "for a decline of 2~m.}", "\\label{tab:ed_h3_2m}"] + header()
    out += body(k, ROWS, ["2"])
    out += ["\\end{tabular}", "\\end{table}", ""]
    return out


def t3_habitat(k: Keys) -> list[str]:
    out = ["\\begin{table}[!htbp]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{2.5pt}",
           "\\caption{\\textbf{Further habitat stand-ins, 1~m and 2~m below the 2026 level (H3).} As Table~\\ref{tab:h3}, "
           "for the emerged area (km\\textsuperscript{2}) of three further open-licence wetland layers: OpenStreetMap "
           "wetlands, GWL\\_FCS30 2020 wetland classes and GLWD v2 wetland classes. They are stand-ins, not "
           "authoritative habitat maps.}",
           "\\label{tab:ed_h3_habitat}"] + header()
    out += body(k, ROWS_ED, ["1", "2"])
    out += ["\\end{tabular}", "\\end{table}", ""]
    return out


def dates_table(k: Keys) -> list[str]:
    sd = pd.read_csv(RESULTS / "emergence" / "main" / "scenario_dates.csv")
    verified = {r["key"] for r in csv.DictReader((C.ROOT / "refs" / "verification.csv").open(encoding="utf-8"))}
    keep = sd[sd["source"].isin(verified)]
    left_out = sorted(set(sd["source"]) - verified)
    scen = sorted(sd["delta_m"].unique())
    lab = {s: f"{s:g}".replace(".", "p") for s in scen}
    role_order = {"primary": 0, "range": 1, "sensitivity": 2}
    paths = keep.drop_duplicates("pathway_id").copy()
    paths["o"] = paths["role"].map(role_order)
    paths = paths.sort_values(["o", "source", "pathway_id"])
    out = ["% Generated by figures/tab_h3.py from results/metrics.json keys. Do not edit.", "",
           "\\begin{table}[!htbp]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
           "\\caption{\\textbf{When published pathways reach each scenario depth.} Calendar year in which each "
           "pathway's own fall after 2026 first reaches the decline below the 2026 level (\\metric{h3.level_2026_m}~m, "
           "DAHITI reference); each pathway is linear between the points its source states, anchored at its reference "
           "year at zero change, and never extrapolated beyond its last stated year. Primary pathways set the "
           "dates quoted in the text; range and sensitivity pathways are reported beside them. --, not reached by "
           "the pathway's last stated year (2100)."
           + (" Pathways from sources whose values we could not verify are not shown." if left_out else "")
           + "}",
           "\\label{tab:ed_scenario_dates}",
           "\\begin{tabular}{p{2.1cm}p{2.5cm}p{3.6cm}l" + "r" * len(scen) + "}", "\\hline",
           "Source & Scenario & Statistic & Role & " + " & ".join(f"{s:g}~m" for s in scen) + " \\\\", "\\hline"]
    for r in paths.itertuples():
        pid = "".join(ch if ch.isalnum() else "_" for ch in str(r.pathway_id).lower())
        pid = "_".join(t for t in pid.split("_") if t)
        cells = []
        for s in scen:
            key = f"h3.date.{pid}.{lab[s]}"
            v = str(k.m.get(key, {}).get("value", ""))
            cells.append(k(key) if v[:1].isdigit() else ("--" if key in k.m else k(key)))
        scen_tex = str(r.scenario).replace("_", "\\_").replace("&", "\\&")
        stat_tex = str(r.statistic).replace("_", "\\_").replace("&", "\\&").replace("%", "\\%")
        out.append(f"{SOURCE_TEX.get(r.source, r.source)} & {scen_tex} & {stat_tex} & {r.role} & " + " & ".join(cells) + " \\\\")
    out += ["\\hline", "\\end{tabular}", "\\end{table}", ""]
    return out


def main() -> int:
    k = Keys(C.metrics())
    block = t3(k)
    ed = dates_table(k) + t3_2m(k) + t3_habitat(k)
    if k.missing:
        print("FAIL missing metric keys:", sorted(set(k.missing))[:20], len(set(k.missing)))
        return 1
    text = TABLES.read_bytes().decode("utf-8").replace("\r\n", "\n")
    lines = text.split("\n")
    if "% BEGIN T3" in text:
        i0 = next(i for i, ln in enumerate(lines) if ln.startswith("% BEGIN T3"))
        i1 = next(i for i, ln in enumerate(lines) if ln.startswith("% END T3"))
    else:   # the stub of the first draft: the table environment labelled tab:h3
        lab = next(i for i, ln in enumerate(lines) if "\\label{tab:h3}" in ln)
        i0 = max(i for i in range(lab) if lines[i].startswith("\\begin{table}"))
        i1 = next(i for i in range(lab, len(lines)) if lines[i].startswith("\\end{table}"))
    new = lines[:i0] + block + lines[i1 + 1:]
    C.write_crlf(TABLES, "\n".join(new))
    C.write_crlf(ED, "\n".join(ed))
    n = sum(ln.count("\\metric{") for ln in block + ed)
    print(f"T3 written into {TABLES.relative_to(C.ROOT).as_posix()}; {ED.relative_to(C.ROOT).as_posix()}; {n} macros")
    return 0


if __name__ == "__main__":
    sys.exit(main())
