"""Write scripts/README.md: an index of every pipeline script, grouped by its step prefix,
with the first line of its docstring. Run after adding or renaming a script.

Usage: python tools/scripts_index.py
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "scripts"

GROUPS = [  # (prefix, heading), in pipeline order
    ("p0", "Input checks (p0)"),
    ("a0", "Study area, sectors, blocks (a0)"),
    ("a1", "Literature (a1)"),
    ("a2", "Scene inventory and ice season (a2)"),
    ("a3", "Water classification (a3; Earth Engine, stage 1)"),
    ("a4", "Water level per scene (a4)"),
    ("a5", "Surge and setup screening (a5)"),
    ("a6", "Stage-2 counts, waterlines, DEM and its validation (a6; H2)"),
    ("a7", "Hindcast audit (a7; H1) and red-team runs"),
    ("a8", "Near-term emergence and exposure (a8; H3)"),
    ("g1", "Generality test: Great Salt Lake (g1)"),
    ("r", "Robustness checks (r)"),
    ("f", "Display-item inputs (f)"),
    ("", "Other"),
]


def first_line(path: Path) -> str:
    try:
        doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8")))
    except (SyntaxError, UnicodeDecodeError):
        doc = None
    return (doc or "").strip().splitlines()[0].strip() if doc else "(no docstring)"


def group_of(name: str) -> str:
    for prefix, _ in GROUPS:
        if prefix and (name.startswith(prefix + "_") or (prefix in ("r", "f") and name[0] == prefix
                                                          and name[1:3].isdigit())):
            return prefix
    return ""


def render() -> str:
    files = sorted(p for p in SCRIPTS.glob("*.py"))
    out = ["# Scripts", "",
           "Pipeline entry points, grouped by pipeline step (the file-name prefix). "
           "`make all` runs the ones that rebuild results from the raw inputs; acquisition steps "
           "(downloads, Earth Engine) have their own targets and never run in `make all`. "
           "Generated by `tools/scripts_index.py`; do not edit by hand.", ""]
    for prefix, heading in GROUPS:
        rows = [p for p in files if group_of(p.stem) == prefix]
        if not rows:
            continue
        out += [f"## {heading}", "", "| Script | Purpose |", "|---|---|"]
        out += [f"| `{p.name}` | {first_line(p).replace('|', '/')} |" for p in rows]
        out.append("")
    return "\n".join(out)


def main() -> int:
    (SCRIPTS / "README.md").write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote scripts/README.md ({len(list(SCRIPTS.glob('*.py')))} scripts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
