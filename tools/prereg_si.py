"""Render the pre-registration as a Supplementary file of the ERL Letter (D-138; reviews R1
minor 17, R2.M12, R3.M7).

Reads docs/PREREG.md and writes manuscript/supplementary_prereg.md: the registration (version
1.0) and every dated amendment and erratum, reproduced verbatim, each preceded by the commit that
first added it to the repository and that commit's date, both taken from git (`git log -S` on the
heading line, oldest first). A part not yet committed is marked so, and a working copy that
differs from the last commit is flagged, so the file never claims a commit that does not exist.

The text keeps the registration's own references to the decision log (D-numbers) and to code and
file paths; they point to the public repository. ERL asks each supplementary file to carry a title
of at most 30 characters and a description of at most 30 words inside it.

Usage: python tools/prereg_si.py [--check]   (--check: exit 1 if the output is out of date)
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "docs" / "PREREG.md"
OUT = ROOT / "manuscript" / "supplementary_prereg.md"
REL = "docs/PREREG.md"

TITLE = "Pre-registration record"      # at most 30 characters (ERL)
DESCRIPTION = ("The study's pre-registration (version 1.0) and every dated amendment and erratum, verbatim, "
               "each with the repository commit and date that first recorded it.")

HEADING = re.compile(r"^## (Amendment \d+)\b(.*)$")
ERRATUM = re.compile(r"^\*\*(Erratum to Amendment \d+[^*]*?)\*\*")


def git(*args: str) -> str:
    r = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, encoding="utf-8")
    return r.stdout.strip() if r.returncode == 0 else ""


def first_commit_with(line: str) -> tuple[str, str]:
    """(short hash, ISO date) of the oldest commit whose diff of docs/PREREG.md adds or removes
    ``line`` (git's pickaxe), or ("", "") when no commit holds it."""
    out = git("log", "--reverse", "--format=%h%x09%ad", "--date=short", "-S", line, "--", REL)
    if not out:
        return "", ""
    h, d = out.splitlines()[0].split("\t")
    return h, d


def created() -> tuple[str, str]:
    out = git("log", "--diff-filter=A", "--reverse", "--format=%h%x09%ad", "--date=short", "--", REL)
    if not out:
        return "", ""
    h, d = out.splitlines()[0].split("\t")
    return h, d


def stated_date(rest: str) -> str:
    m = re.search(r"\d{4}-\d{2}-\d{2}(?:\s+\d{2}:\d{2})?", rest)
    return m.group(0) if m else ""


def render() -> str:
    lines = SRC.read_text(encoding="utf-8").splitlines()
    parts = []                                   # (label, stated date, hash, commit date, line index)
    h0, d0 = created()
    parts.append(("Registration, version 1.0", "2026-10-20", h0, d0, None))
    for i, ln in enumerate(lines):
        m = HEADING.match(ln)
        e = ERRATUM.match(ln)
        if m:
            h, d = first_commit_with(ln)
            parts.append((m.group(1), stated_date(m.group(2)), h, d, i))
        elif e:
            label = e.group(1).strip().rstrip(".")
            h, d = first_commit_with(ln[:120])
            parts.append((label.split(" (")[0], stated_date(label), h, d, i))
    dirty = subprocess.run(["git", "diff", "--quiet", "HEAD", "--", REL], cwd=ROOT).returncode != 0
    head = git("rev-parse", "--short", "HEAD")

    out = [f"# {TITLE}", "",
           f"**Description.** {DESCRIPTION}", "",
           "Supplementary file of: *Four decades of retreating shorelines audit projected seabed emergence in the "
           "North Caspian Sea* (Environmental Research Letters, submitted).", "",
           f"Generated by `tools/prereg_si.py` from `{REL}` of the public repository "
           "(https://github.com/rezw4n/north-caspian-emergence)"
           + (f" at commit `{head}`" if head else "") + ". The text below is the registration file verbatim; its "
           "references to the decision log (D-numbers), to code and to files point to that repository. The commit "
           "and date of each part are read from git: the oldest commit that added the part's heading.", ""]
    if dirty:
        out += ["**Note.** The working copy of the registration differs from its last commit; parts marked "
                "\"not committed\" exist only in the working copy.", ""]
    out += ["| Part | Date stated in the text | Commit | Commit date |", "|---|---|---|---|"]
    for label, sd, h, d, _ in parts:
        out.append(f"| {label} | {sd or '—'} | {('`' + h + '`') if h else 'not committed'} | {d or '—'} |")
    out += ["", "---", ""]
    marks = {i: (h, d) for _, _, h, d, i in parts if i is not None}
    for i, ln in enumerate(lines):
        out.append(ln)
        if i in marks:
            h, d = marks[i]
            out += ["", f"*Recorded in commit `{h}` on {d}.*" if h else "*Not committed at the time of rendering.*", ""]
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("supplementary_prereg.md is " + ("current" if ok else "out of date"))
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    n = text.count("*Recorded in commit") + text.count("*Not committed")
    print(f"wrote {OUT.relative_to(ROOT)} ({n} amendments and errata)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
